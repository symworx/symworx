//! Run Performance simulation and modeling.
//!
//! This module provides tool and utilities to model running performance
//! based on interactions between physiological and biomechanical factors.
//! Further, this module provides the ability to estimate the effect of the
//! shoe on run perfomrance.
//!
//! Legacy implementations of this modeling framework contained parametric
//! models that emphasized modeling fatigue and subsequently overlaying
//! estimates of gait and physiological dynamics.
//!
//! Instead of migrating this legacy framework, this module will remain a
//! work in progress as a more comprehensive and realistic model is developed.
//! The foundation of this model was previously built (but a migration was never
//! completed). Instead of focusing time on building out an obsolete model,
//! we'll complete the play as part of the larger `symworx-to-rust` effort.
